export function makeCombatant(
  defId: string,
  overrides: Partial<CombatantState> & { name?: string } = {},
): CombatantState {
  const def = CHARACTERS[defId];
  if (!def) throw new Error(`Unknown character ${defId}`);
  return {
    id: overrides.id ?? def.id,
    name: overrides.name ?? def.name,
    side: "party",
    jobId: def.jobId,
    level: 3,
    hp: def.base.maxHp,
    maxHp: def.base.maxHp,
    mp: def.base.maxMp,
    maxMp: def.base.maxMp,
    attack: def.base.attack,
    defense: def.base.defense,
    speed: def.base.speed,
    resistances: {},
    statuses: [],
    cooldowns: {},
    initiativeDebt: 0,
    alive: true,
    position: overrides.position ?? { x: 0, z: 0 },
  };
}

